import { chromium } from 'file:///C:/Users/JoelWang/Documents/dev/ember-vale/node_modules/playwright-core/index.mjs'
const [out, id] = process.argv.slice(2)
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
page.on('pageerror', (e) => console.log('page error:', e.message))
page.on('console', (m) => m.type() === 'error' && console.log('console error:', m.text()))
const waitGone = async (text) => {
  await page.waitForSelector(`text=${text}`, { timeout: 10000 }).catch(() => {})
  await page.waitForFunction((t) => !document.body.innerText.includes(t), text, { timeout: 300000 })
}
await page.goto(`http://localhost:5180/library/world/${id}/map`, { waitUntil: 'load', timeout: 90000 })
await page.getByRole('button', { name: 'Use the world’s picture' }).click({ timeout: 60000 })
await page.waitForSelector('.mapframe img')
await page.getByRole('button', { name: /Find the places/ }).first().click()
await waitGone('Reading the map')
console.log('kept places:', await page.locator('.pin:not(.pin--off)').count())
await page.getByRole('button', { name: /Trace the roads/ }).first().click()
await waitGone('Tracing')
await page.waitForTimeout(1500)
console.log('notice:', (await page.locator('.card__note').allTextContents()).join(' | ').slice(0, 300))
await page.getByRole('button', { name: 'Terrain' }).click()
await page.getByRole('button', { name: 'Read the terrain' }).click()
await waitGone('Reading the terrain')
await page.waitForTimeout(1200)
console.log('terrain notice:', (await page.locator('.card__note').allTextContents()).join(' | ').slice(0, 300))
console.log('legend:', (await page.locator('.legend').last().innerText()).replace(/\n/g, ' · '))
const frame = page.locator('.mapframe')
await frame.scrollIntoViewIfNeeded()
await page.screenshot({ path: `${out}/terrain-read.png`, fullPage: true })
// paint a band of mountains across the middle with a 3x3 brush
await page.getByRole('radio', { name: /Mountains/ }).click()
await page.locator('select[aria-label="Brush size"]').selectOption('1')
const b = await frame.boundingBox()
await page.mouse.move(b.x + b.width * 0.3, b.y + b.height * 0.55)
await page.mouse.down()
for (let i = 0; i <= 10; i++) await page.mouse.move(b.x + b.width * (0.3 + i * 0.03), b.y + b.height * 0.55)
await page.mouse.up()
await page.waitForTimeout(500)
console.log('after paint:', (await page.locator('.legend').last().innerText()).replace(/\n/g, ' · '))
await page.screenshot({ path: `${out}/terrain-painted.png`, fullPage: true })
await page.getByRole('button', { name: 'Done with the terrain' }).click()
await page.getByRole('button', { name: /Save the map/ }).click()
await page.waitForFunction(() => document.body.innerText.includes('All changes saved') || document.querySelector('[role=alert]'), null, { timeout: 60000 })
console.log('alerts:', await page.locator('[role=alert]').allTextContents())
const detail = await page.evaluate(async (id) => (await fetch(`/api/v1/library/presets/${id}`)).json(), id)
const map = detail.revision.map
console.log('saved terrain:', map.terrain ? `${map.terrain.cols}x${map.terrain.rows}` : null, 'roads:', map.roads.map((r) => `${r.a}-${r.b}:${r.phases}`).join(', '))
await browser.close()
