import { chromium } from 'file:///C:/Users/JoelWang/Documents/dev/ember-vale/node_modules/playwright-core/index.mjs'
const out = process.argv[2]
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
page.on('pageerror', (e) => console.log('page error:', e.message))
page.on('console', (m) => m.type() === 'error' && console.log('console error:', m.text()))
const shot = (n) => page.screenshot({ path: `${out}/${n}.png`, fullPage: true })
// A · the character, made in the studio
await page.goto('http://localhost:5180/library/character/new', { waitUntil: 'load', timeout: 90000 })
await page.waitForSelector('.cstudio')
await page.fill('#c-name', 'Mara Vell')
await page.fill('#c-pronouns', 'she/her')
await page.fill('.ovw__text', 'ferry-clan girl, 17, apprenticed to the bell-keepers of the Saltreach. curious, stubborn, a bit reckless. wants to hear the drowned bells up close and learn why the city sank. carries a tide-knife and her grandmother\'s brass bell.')
await page.locator('.ovw__btn--fill').click()
await page.waitForFunction(() => !document.querySelector('.ovw__btn--fill')?.textContent?.includes('Filling'), null, { timeout: 200000 })
console.log('fill:', await page.locator('.ovw__note').allTextContents())
await page.locator('.istep__step button').nth(1).click()
await page.waitForTimeout(400)
await page.locator('.pick__paint').click()
await page.waitForFunction(() => !document.querySelector('.pick__paint')?.textContent?.includes('Painting'), null, { timeout: 300000 })
console.log('paint error:', await page.locator('.pick__error').allTextContents())
await page.waitForTimeout(1200)
await shot('a-character')
await page.locator('.istep__step button').nth(4).click()
await page.getByRole('button', { name: 'Create character' }).click()
await page.waitForURL(/\/library\/character\/[0-9a-f-]{36}$/, { timeout: 60000 })
console.log('character ->', page.url())
// B · the story, through the wizard
await page.goto('http://localhost:5180/new-story', { waitUntil: 'load' })
await page.waitForSelector('.nsv__worlds', { timeout: 60000 })
await page.waitForTimeout(1000)
await page.locator('.nsv__world', { hasText: 'The Saltreach' }).first().click()
await page.getByRole('button', { name: 'Continue' }).click()
await page.waitForTimeout(1200)
for (const who of ['Mara Vell', 'Ash']) {
  const card = page.locator('.cast', { hasText: who }).first()
  if ((await card.getAttribute('aria-pressed')) !== 'true') await card.click()
}
await page.waitForTimeout(600)
await shot('b-cast')
await page.getByRole('button', { name: 'Continue' }).click()
await page.waitForTimeout(800)
await page.locator('.nsv__world', { hasText: 'Player' }).click()
const opts = await page.locator('.nsv__panel select option').allTextContents()
console.log('play as options:', opts)
const mara = opts.find((o) => o.includes('Mara'))
if (mara) await page.locator('.nsv__panel select').first().selectOption({ label: mara })
await page.getByRole('button', { name: 'Continue' }).click()
await page.waitForTimeout(800)
await page.locator('.nsv__panel input').first().fill('The Bells of the Saltreach')
await page.getByRole('button', { name: 'Continue' }).click()
await page.waitForTimeout(800)
await page.getByRole('button', { name: 'Continue' }).click()
await page.waitForTimeout(1500)
await shot('c-review')
console.log('issues:', await page.locator('.nsv__issues').allTextContents())
await page.getByRole('button', { name: 'Begin the story' }).click()
await page.waitForURL(/\/stories\/[0-9a-f-]{36}\//, { timeout: 120000 })
console.log('story ->', page.url())
await page.waitForTimeout(5000)
await shot('d-opened')
await browser.close()
