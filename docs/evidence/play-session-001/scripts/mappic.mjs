import { chromium } from 'file:///C:/Users/JoelWang/Documents/dev/ember-vale/node_modules/playwright-core/index.mjs'
const [out, id] = process.argv.slice(2)
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
page.on('pageerror', (e) => console.log('page error:', e.message))
page.on('console', (m) => m.type() === 'error' && console.log('console error:', m.text()))
await page.goto(`http://localhost:5180/library/world/${id}/map`, { waitUntil: 'load', timeout: 90000 })
await page.getByRole('button', { name: 'Use the world’s picture' }).click({ timeout: 60000 })
await page.waitForSelector('.mapframe img', { timeout: 60000 })
console.log('notice:', await page.locator('.card__note, [role=status]').allTextContents())
const find = page.getByRole('button', { name: /Find the places/ }).first()
const t = Date.now()
await find.click()
await page.waitForSelector('text=Reading the map', { timeout: 10000 }).catch(() => console.log('never saw reading'))
await page.waitForFunction(() => !document.body.innerText.includes('Reading the map'), null, { timeout: 200000 })
console.log('errors:', await page.locator('[role=alert]').allTextContents())
await page.waitForTimeout(2000)
console.log('names:', (await page.locator('.pin').evaluateAll((els) => els.map((e) => e.textContent?.trim()).filter(Boolean))).join(' | '))
console.log('found in', (Date.now() - t) / 1000, 's; pins:', await page.locator('.pin').count())
await page.screenshot({ path: `${out}/map-from-world-picture.png`, fullPage: true })
await browser.close()
