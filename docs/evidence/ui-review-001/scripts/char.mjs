import { chromium } from 'file:///C:/Users/JoelWang/Documents/dev/ember-vale/node_modules/playwright-core/index.mjs'
const [out, live] = process.argv.slice(2)
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
page.on('pageerror', (e) => console.log('page error:', e.message))
page.on('console', (m) => m.type() === 'error' && console.log('console error:', m.text()))
await page.goto('http://localhost:5180/library/character/new', { waitUntil: 'load', timeout: 90000 })
await page.waitForSelector('.cstudio', { timeout: 60000 })
await page.waitForTimeout(800)
await page.fill('#c-name', 'Tamsin Reed')
await page.fill('.ovw__text', 'young river-smuggler, half-elf, quick tongue, lost her boat to the toll-wardens, wants it back. scar on chin. carries a bone whistle')
await page.screenshot({ path: `${out}/1-overview.png`, fullPage: true })
if (live === 'live') {
  const t0 = Date.now()
  await page.getByRole('button', { name: 'Improve my overview' }).click()
  await page.waitForSelector('.ovw__proposal', { timeout: 150000 })
  console.log('improve took', (Date.now() - t0) / 1000, 's')
  console.log('proposal:', (await page.locator('.ovw__proposal-text').textContent()).slice(0, 400))
  await page.screenshot({ path: `${out}/1b-proposal.png`, fullPage: true })
  await page.getByRole('button', { name: 'Use this one' }).click()
  const t1 = Date.now()
  await page.locator('.ovw__btn--fill').click()
  await page.waitForFunction(() => !document.querySelector('.ovw__btn--fill')?.textContent?.includes('Filling'), null, { timeout: 200000 })
  console.log('fill took', (Date.now() - t1) / 1000, 's')
  console.log('notes:', await page.locator('.ovw__note').allTextContents())
}
for (const n of [2, 3, 4, 5]) {
  await page.locator('.istep__step button').nth(n - 1).click()
  await page.waitForTimeout(700)
  await page.screenshot({ path: `${out}/${n}-step.png`, fullPage: true })
}
if (live === 'live') {
  await page.locator('.istep__step button').nth(1).click()
  await page.waitForTimeout(600)
  console.log('paint prompt:', await page.locator('.pick__paint').getAttribute('title'))
  const t2 = Date.now()
  await page.locator('.pick__paint').click()
  await page.waitForFunction(() => !document.querySelector('.pick__paint')?.textContent?.includes('Painting'), null, { timeout: 300000 })
  console.log('paint took', (Date.now() - t2) / 1000, 's', 'error:', await page.locator('.pick__error').allTextContents())
  await page.waitForTimeout(1500)
  await page.screenshot({ path: `${out}/2b-painted.png`, fullPage: true })
}
const over = await page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth)
console.log('overflow', over)
await page.setViewportSize({ width: 400, height: 900 })
await page.waitForTimeout(500)
console.log('phone overflow', await page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth))
await page.screenshot({ path: `${out}/phone.png`, fullPage: true })
await browser.close()
