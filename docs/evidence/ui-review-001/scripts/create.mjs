import { chromium } from 'file:///C:/Users/JoelWang/Documents/dev/ember-vale/node_modules/playwright-core/index.mjs'
const out = process.argv[2]
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
page.on('pageerror', (e) => console.log('page error:', e.message))
await page.goto('http://localhost:5180/library/character/new', { waitUntil: 'load', timeout: 90000 })
await page.waitForSelector('.cstudio')
await page.fill('#c-name', 'Probe Wren-Test')
await page.fill('.ovw__text', 'A test character made by the studio check; safe to archive.')
await page.locator('.istep__step button').nth(1).click()
await page.fill('#c-age', '30')
await page.getByRole('button', { name: 'Female', exact: true }).click()
await page.fill('#c-hair', 'short black hair')
await page.locator('.istep__step button').nth(4).click()
await page.fill('#c-wears', 'a grey cloak')
await page.getByRole('button', { name: 'Create character' }).click()
await page.waitForURL(/\/library\/character\/[0-9a-f-]{36}$/, { timeout: 60000 })
console.log('created ->', page.url())
await page.waitForTimeout(2500)
console.log('reopened age:', await page.locator('.istep__step button').nth(1).click().then(() => page.inputValue('#c-age')))
console.log('reopened sex on:', await page.locator('.seg__opt--on').allTextContents())
await page.goto('http://localhost:5180/library?tab=characters', { waitUntil: 'load' })
await page.waitForSelector('.libcard')
await page.waitForTimeout(1200)
const card = page.locator('.libcard', { hasText: 'Probe Wren-Test' })
console.log('card bio:', await card.locator('.libcard__bio').textContent())
await card.locator('.cmenu__dots').click()
await page.getByRole('menuitem', { name: 'Archive' }).click()
await page.waitForSelector('.lib__toast')
console.log('toast:', await page.locator('.lib__toast span').textContent())
await page.waitForTimeout(800)
console.log('card gone:', (await page.locator('.libcard', { hasText: 'Probe Wren-Test' }).count()) === 0)
await page.screenshot({ path: `${out}/archived-toast.png` })
await browser.close()
