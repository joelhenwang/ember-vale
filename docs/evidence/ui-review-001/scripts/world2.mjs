import { chromium } from 'file:///C:/Users/JoelWang/Documents/dev/ember-vale/node_modules/playwright-core/index.mjs'
const out = process.argv[2]
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
page.on('pageerror', (e) => console.log('page error:', e.message))
page.on('console', (m) => m.type() === 'error' && console.log('console error:', m.text()))
await page.goto('http://localhost:5180/library/world/new', { waitUntil: 'load', timeout: 90000 })
await page.waitForSelector('.wstudio')
await page.fill('#w-name', 'The Saltreach')
await page.fill('.ovw__text', 'salt-marsh islands, ferry clans keep water roads, tides set the calendar, drowned city under the bay rings bells at low tide. no gunpowder.')
await page.locator('.ovw__btn--fill').click()
await page.waitForFunction(() => !document.querySelector('.ovw__btn--fill')?.textContent?.includes('Filling'), null, { timeout: 200000 })
console.log(await page.locator('.ovw__note').allTextContents())
await page.locator('.istep__step button').nth(2).click()
await page.waitForTimeout(500)
console.log('on tabs:', await page.locator('.places__tab--on').count(), 'of', await page.locator('.places__tab').count())
await page.locator('.wpv .cta').first().click()
await page.waitForFunction(() => !document.querySelector('.wpv .cta')?.textContent?.includes('Painting'), null, { timeout: 300000 })
await page.locator('.istep__step button').nth(3).click()
await page.waitForTimeout(500)
await page.screenshot({ path: `${out}/7-review.png`, fullPage: true })
await page.getByRole('button', { name: 'Create world' }).click()
await page.waitForURL(/\/library\/world\/[0-9a-f-]{36}$/, { timeout: 60000 })
console.log('created ->', page.url())
await page.waitForTimeout(3000)
await page.getByRole('tab', { name: 'Place' }).click()
await page.waitForTimeout(800)
const t = Date.now()
await page.locator('#wpanel-panel-place .cta').click()
await page.waitForFunction(() => !document.querySelector('#wpanel-panel-place .cta')?.textContent?.includes('Painting'), null, { timeout: 300000 })
console.log('place paint', (Date.now() - t) / 1000, 's', await page.locator('#wpanel-panel-place .wpv__note, #wpanel-panel-place .wpv__error').allTextContents())
await page.waitForTimeout(1500)
await page.screenshot({ path: `${out}/8-place-painted.png`, fullPage: true })
// publish a change after the place picture: the picture must survive
await page.locator('.istep__step button').nth(1).click()
await page.waitForTimeout(400)
await page.fill('#w-exclusions', 'Gunpowder, guns, steam engines, and dragons')
await page.locator('.istep__step button').nth(3).click()
await page.waitForTimeout(400)
await page.getByRole('button', { name: 'Publish changes' }).click()
await page.waitForFunction(() => document.body.textContent?.includes('Published revision'), null, { timeout: 60000 })
console.log('published:', (await page.locator('.studio__state').allTextContents()).join(' | '))
const id = page.url().split('/').pop()
const detail = await page.evaluate(async (id) => {
  const r = await fetch(`/api/v1/library/presets/${id}`)
  return r.json()
}, id)
console.log('revision', detail.current_revision, 'place maps kept:', detail.revision.locations.filter((l) => l.map).map((l) => l.name), 'exclusions in lore:', detail.revision.lore.includes('dragons'))
console.log('cover kept:', !!detail.revision.cover)
await browser.close()
