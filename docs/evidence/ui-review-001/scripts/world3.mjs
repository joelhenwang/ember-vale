import { chromium } from 'file:///C:/Users/JoelWang/Documents/dev/ember-vale/node_modules/playwright-core/index.mjs'
const [out, id] = process.argv.slice(2)
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
page.on('pageerror', (e) => console.log('page error:', e.message))
page.on('console', (m) => m.type() === 'error' && console.log('console error:', m.text()))
await page.goto(`http://localhost:5180/library/world/${id}`, { waitUntil: 'load', timeout: 90000 })
await page.waitForSelector('.wstudio')
await page.waitForTimeout(3000)
await page.getByRole('tab', { name: 'Place' }).click()
await page.locator('.wpv__chip').nth(1).click()
await page.waitForTimeout(500)
const t = Date.now()
await page.locator('#wpanel-panel-place .cta').click()
await page.waitForFunction(() => !document.querySelector('#wpanel-panel-place .cta')?.textContent?.includes('Painting'), null, { timeout: 300000 })
console.log('place paint', (Date.now() - t) / 1000, 's', await page.locator('#wpanel-panel-place .wpv__note, #wpanel-panel-place .wpv__error').allTextContents())
await page.waitForTimeout(1200)
await page.screenshot({ path: `${out}/8-place-painted.png`, fullPage: true })
await page.locator('.istep__step button').nth(1).click()
await page.waitForTimeout(400)
await page.fill('#w-exclusions', 'Gunpowder, guns, steam engines, and dragons')
await page.locator('.istep__step button').nth(3).click()
await page.waitForTimeout(400)
await page.getByRole('button', { name: 'Publish changes' }).click()
await page.waitForFunction(() => /Published revision|failed|Conflict|conflict/.test(document.body.textContent ?? ''), null, { timeout: 60000 })
console.log('state:', (await page.locator('.studio__state').allTextContents()).join(' | '))
const detail = await page.evaluate(async (id) => (await fetch(`/api/v1/library/presets/${id}`)).json(), id)
console.log('revision', detail.current_revision, 'place maps kept:', detail.revision.locations.filter((l) => l.map).map((l) => l.name), 'dragons:', detail.revision.lore.includes('dragons'), 'cover:', !!detail.revision.cover)
await browser.close()
